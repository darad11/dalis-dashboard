-- ============================================================
-- Calendar: start/end times and own calendars for calendar entries
-- Run once in the Supabase SQL Editor. Safe to run again: every
-- statement is idempotent. Existing rows are not changed: the new
-- columns are NULL, which means "all-day entry in the default
-- calendar" - exactly what every existing entry is today.
--
-- Calendar entries are the rows of public.goals whose date starts
-- with 'cal-' (daily goals use 'goals-' and leave the columns NULL).
-- The calendars themselves (name, colour) live in public.settings
-- under the key 'calendars'. Row Level Security is unchanged: the
-- existing goals policies (auth.uid() = user_id) cover the new columns.
-- ============================================================

alter table public.goals
    add column if not exists start_time  time,   -- local wall-clock start (NULL = all-day entry)
    add column if not exists end_time    time,   -- local wall-clock end on the same day
    add column if not exists calendar_id text;   -- id from settings 'calendars' (NULL = default calendar)

comment on column public.goals.start_time is 'Calendar entry start, local time of the day (NULL = all-day)';
comment on column public.goals.end_time is 'Calendar entry end, same day, not before start_time';
comment on column public.goals.calendar_id is 'Calendar id from settings key ''calendars'' (NULL = default calendar)';

-- An end needs a start and is not before it (entries never span midnight);
-- calendar ids are short identifiers generated by the dashboard
do $$
begin
    if not exists (select 1 from pg_constraint
                   where conname = 'goals_time_range_check' and conrelid = 'public.goals'::regclass) then
        alter table public.goals add constraint goals_time_range_check
            check (end_time is null or (start_time is not null and end_time >= start_time));
    end if;
    if not exists (select 1 from pg_constraint
                   where conname = 'goals_calendar_id_check' and conrelid = 'public.goals'::regclass) then
        alter table public.goals add constraint goals_calendar_id_check
            check (calendar_id is null or char_length(calendar_id) between 1 and 64);
    end if;
end;
$$;

-- Make the API (PostgREST) see the new columns right away
notify pgrst, 'reload schema';
